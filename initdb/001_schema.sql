-- งาน: สร้างตาราง SOURCE, LOCATION, PROCESS, FLOW, PROCESS_FLOW, UNIT และ LCI_EXCHANGE
-- ใช้สำหรับเตรียมโครงสร้างฐานข้อมูลตาม ERD ก่อนเพิ่มข้อมูล
-- CN230 LCI project: initial PostgreSQL schema
-- Files in initdb run only when Docker creates the database volume for the first time.

CREATE TABLE source (
    source_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    src_code        varchar(20) NOT NULL UNIQUE,
    dataset_name    text NOT NULL,
    agency          text NOT NULL,
    data_owner      text NOT NULL,
    url             text,
    accessed_date   date
);

CREATE TABLE location (
    location_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country     text NOT NULL UNIQUE
);

CREATE TABLE process (
    process_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Short context only: e.g. SIRIKIT, BANGCHAK, INDUSTRY, NATIONAL.
    name         text NOT NULL,
    process_type text NOT NULL CHECK (process_type IN (
        'PRODUCTION', 'IMPORT', 'EXPORT', 'REFINING',
        'DOMESTIC_USE', 'DISTRIBUTION', 'EMISSION'
    )),
    location_id  integer NOT NULL REFERENCES location(location_id),
    UNIQUE (name, process_type, location_id)
);

CREATE TABLE flow (
    flow_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         text NOT NULL UNIQUE,
    product_type text NOT NULL CHECK (product_type IN (
        'OIL', 'NATURAL_GAS', 'COAL', 'BIOFUEL', 'EMISSION'
    ))
);

CREATE TABLE process_flow (
    process_flow_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    process_id      integer NOT NULL REFERENCES process(process_id),
    flow_id         integer NOT NULL REFERENCES flow(flow_id),
    direction       text NOT NULL CHECK (direction IN ('IN', 'OUT')),
    UNIQUE (process_id, flow_id)
);

CREATE TABLE unit (
    unit_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol        varchar(40) NOT NULL UNIQUE,
    quantity_type text NOT NULL CHECK (quantity_type IN (
        'VOLUME', 'VOLUME_RATE', 'MASS', 'GAS_RATE'
    )),
    to_base_factor numeric(20, 10) NOT NULL CHECK (to_base_factor > 0)
);

CREATE TABLE lci_exchange (
    exchange_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    process_flow_id   integer NOT NULL REFERENCES process_flow(process_flow_id),
    amount            numeric(24, 8) NOT NULL,
    unit_id           integer NOT NULL REFERENCES unit(unit_id),
    period_year       integer NOT NULL CHECK (period_year BETWEEN 1 AND 9999),
    period_month      integer CHECK (period_month BETWEEN 1 AND 12),
    source_id         integer NOT NULL REFERENCES source(source_id),
    validation_status text NOT NULL DEFAULT 'PENDING' CHECK (
        validation_status IN ('PENDING', 'VERIFIED', 'ERROR')
    ),
    note              text
);

-- บันทึกแถวจาก CSV ที่นำเข้าไม่ได้หรือข้ามโดยตั้งใจ แยกจาก Exchange ที่สมบูรณ์
CREATE TABLE lci_import_log (
    import_log_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id     integer NOT NULL REFERENCES source(source_id),
    source_line   integer NOT NULL,
    status        text NOT NULL CHECK (status IN ('ERROR', 'SKIPPED')),
    reason        text NOT NULL,
    raw_data      jsonb NOT NULL DEFAULT '{}'::jsonb,
    first_seen_at timestamptz NOT NULL DEFAULT now(),
    last_seen_at  timestamptz NOT NULL DEFAULT now(),
    resolved_at   timestamptz,
    UNIQUE (source_id, source_line)
);

CREATE INDEX idx_process_location ON process(location_id);
CREATE INDEX idx_process_flow_flow ON process_flow(flow_id);
CREATE INDEX idx_exchange_process_flow ON lci_exchange(process_flow_id);
CREATE INDEX idx_exchange_period ON lci_exchange(period_year, period_month);
CREATE INDEX idx_exchange_source ON lci_exchange(source_id);
CREATE INDEX idx_import_log_status ON lci_import_log(status, resolved_at);
