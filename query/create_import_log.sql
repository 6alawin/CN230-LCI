-- เตรียมตารางบันทึกแถว CSV ที่นำเข้าไม่ได้หรือข้ามโดยตั้งใจ
-- รันได้ซ้ำอย่างปลอดภัย
CREATE TABLE IF NOT EXISTS lci_import_log (
    import_log_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id     integer NOT NULL REFERENCES source(source_id),
    source_line   integer NOT NULL,
    status        text NOT NULL CHECK (status IN ('ERROR', 'SKIPPED')),
    reason        text NOT NULL,
    raw_data      jsonb NOT NULL DEFAULT '{}'::jsonb,
    first_seen_at timestamptz NOT NULL DEFAULT now(),
    last_seen_at  timestamptz NOT NULL DEFAULT now(),
    resolved_at   timestamptz,
    UNIQUE (source_id, source_line)
);

CREATE INDEX IF NOT EXISTS idx_import_log_status
    ON lci_import_log(status, resolved_at);
